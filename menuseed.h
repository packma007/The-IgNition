// MVP 메뉴판 15가지를 만들어 주는 곳.
//
// !! 여기 적힌 영양성분은 우리가 실제로 조리해서 잰 값이 아니다.
//    인터넷에 공개된 표준 영양성분표(식약처 식품영양성분DB 등)에서 가져온 근사치다.
//    조리법이 정해지고 실제로 계량하면 이 표를 그 값으로 갈아끼워야 한다.
//    그전까지 이 숫자로 나온 계산은 "대략 이 정도" 이지 정확한 값이 아니다.
//
//    특히 조림/볶음류는 기름과 설탕/간장을 얼마나 쓰느냐에 따라 열량이 크게 흔들린다.
//    같은 "제육볶음" 이라도 집집마다 100g 당 170~250kcal 사이를 오간다.
//    아래 값은 그 가운데를 잡은 것이다.
//
// 표 (100g 당 / 낱개 메뉴는 1개당)
//
//   메뉴                    탄수   단백   지방   kcal   판매 단위
//   ---------------------------------------------------------------
//   잡곡밥                  33.0    3.5    0.6    151   g   100~400
//   고구마구이              31.0    1.6    0.2    132   g    50~300
//   감자조림                20.0    2.0    3.0    115   g    50~250
//   간장닭가슴살구이         3.5   27.0    2.5    145   g    50~300
//   닭가슴살 카레볶음        6.0   24.0    5.0    165   g    50~300
//   소고기 장조림            5.0   21.0    6.0    158   g    30~200
//   두부조림                 4.0    9.5    6.5    113   g    50~250
//   새우 브로콜리 볶음       4.5   12.0    4.0    102   g    50~250
//   간장 닭다리살 구이       4.0   19.0    9.0    173   g    50~300
//   제육볶음                 7.0   15.0   13.0    205   g    50~300
//   고등어구이               0.0   20.0   15.0    215   1토막 = 70g
//   계란말이                 2.5   11.0   11.0    153   1줄  = 60g
//   삼겹살 김치볶음          4.0   11.0   22.0    258   g    50~250
//   버섯볶음                 5.0    3.0    5.0     77   g    30~200
//   브로콜리 참깨무침        6.0    4.0    4.5     81   g    30~200
//
// 고등어구이와 계란말이만 낱개로 판다. 나머지는 g 단위로 담으므로
// MealPlanner 가 양을 자유롭게 조절할 수 있다.
namespace domains {

    // 그 날이 속한 주(일~토)의 메뉴판. 15가지가 모두 채워져 나온다.
    WeeklyMenu mvpWeeklyMenu(const Date& anyDayOfWeek);

    // 오늘이 속한 주
    WeeklyMenu mvpWeeklyMenu();

    // 메뉴 하나만 필요할 때 (테스트/미리보기용). 이름이 없으면 널.
    MenuPtr mvpMenu(const std::string& name);

    // 이번 주 메뉴 이름 15개. 화면에 목록을 그릴 때 쓴다.
    std::vector<std::string> mvpMenuNames();

}

#endif
